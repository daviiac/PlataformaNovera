'use strict';

/**
 * Acesso ao banco Postgres.
 *  - Produção (Vercel): Postgres do Supabase via DATABASE_URL (use a URL do pooler, porta 6543).
 *  - Desenvolvimento/testes: PGlite (Postgres em WebAssembly), sem instalar nada.
 *
 * API: query(sql, params) -> rows · one(sql, params) -> primeira linha ou null.
 * O schema é criado automaticamente na primeira consulta de cada instância.
 */
const fs = require('node:fs');
const { DATABASE_URL, PGLITE_DIR, IS_VERCEL } = require('./config');

const SCHEMA = `
  CREATE TABLE IF NOT EXISTS app_schema (
    id      INTEGER PRIMARY KEY,
    version TEXT    NOT NULL
  );

  CREATE TABLE IF NOT EXISTS users (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          TEXT        NOT NULL,
    email         TEXT        UNIQUE,
    username      TEXT        UNIQUE,
    password_hash TEXT        NOT NULL,
    role          TEXT        NOT NULL DEFAULT 'student' CHECK (role IN ('student', 'admin', 'teacher')),
    level         TEXT        CHECK (level IN ('A1', 'A2', 'B2')),
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (email IS NOT NULL OR username IS NOT NULL)
  );

  CREATE TABLE IF NOT EXISTS sessions (
    token_hash TEXT    PRIMARY KEY,
    user_id    INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    expires_at BIGINT  NOT NULL
  );
  CREATE INDEX IF NOT EXISTS idx_sessions_user ON sessions(user_id);

  CREATE TABLE IF NOT EXISTS placement_results (
    id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    INTEGER     NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    level      TEXT        NOT NULL CHECK (level IN ('A1', 'A2', 'B2')),
    score      INTEGER     NOT NULL,
    max_score  INTEGER     NOT NULL,
    details    JSONB       NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
  );
  CREATE INDEX IF NOT EXISTS idx_placement_user ON placement_results(user_id);

  CREATE TABLE IF NOT EXISTS modules (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    track       TEXT        NOT NULL CHECK (track IN ('A1', 'A2', 'B2')),
    title       TEXT        NOT NULL,
    description TEXT        NOT NULL DEFAULT '',
    position    INTEGER     NOT NULL DEFAULT 0,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (track, title)
  );

  CREATE TABLE IF NOT EXISTS materials (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    module_id     INTEGER     NOT NULL REFERENCES modules(id) ON DELETE CASCADE,
    title         TEXT        NOT NULL,
    description   TEXT        NOT NULL DEFAULT '',
    original_name TEXT        NOT NULL,
    stored_name   TEXT        NOT NULL UNIQUE,
    mime_type     TEXT        NOT NULL,
    kind          TEXT        NOT NULL,
    size_bytes    BIGINT      NOT NULL,
    uploaded_by   INTEGER     REFERENCES users(id) ON DELETE SET NULL,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
  );
  CREATE INDEX IF NOT EXISTS idx_materials_module ON materials(module_id);

  CREATE TABLE IF NOT EXISTS auth_attempts (
    key      TEXT    PRIMARY KEY,
    count    INTEGER NOT NULL,
    reset_at BIGINT  NOT NULL
  );
  CREATE INDEX IF NOT EXISTS idx_auth_attempts_reset ON auth_attempts(reset_at);

  CREATE TABLE IF NOT EXISTS activities (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type        TEXT        NOT NULL,
    level       TEXT        NOT NULL CHECK (level IN ('A1', 'A2', 'B2')),
    title       TEXT        NOT NULL,
    description TEXT        NOT NULL DEFAULT '',
    data        JSONB       NOT NULL,
    created_by  INTEGER     REFERENCES users(id) ON DELETE SET NULL,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
  );
  CREATE INDEX IF NOT EXISTS idx_activities_type_level ON activities(type, level);

  CREATE TABLE IF NOT EXISTS activity_attempts (
    id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      INTEGER     NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    activity_key TEXT        NOT NULL,
    score        INTEGER     NOT NULL,
    total        INTEGER     NOT NULL,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now()
  );
  CREATE INDEX IF NOT EXISTS idx_attempts_user_activity ON activity_attempts(user_id, activity_key);

  CREATE TABLE IF NOT EXISTS level_changes (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     INTEGER     NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    from_level  TEXT        CHECK (from_level IN ('A1', 'A2', 'B2')),
    to_level    TEXT        NOT NULL CHECK (to_level IN ('A1', 'A2', 'B2')),
    changed_by  INTEGER     REFERENCES users(id) ON DELETE SET NULL,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
  );
  CREATE INDEX IF NOT EXISTS idx_level_changes_user ON level_changes(user_id);

  CREATE TABLE IF NOT EXISTS homework_files (
    key         TEXT        PRIMARY KEY,
    stored_name TEXT        NOT NULL UNIQUE,
    size_bytes  BIGINT      NOT NULL,
    uploaded_by INTEGER     REFERENCES users(id) ON DELETE SET NULL,
    uploaded_at TIMESTAMPTZ NOT NULL DEFAULT now()
  );

  CREATE TABLE IF NOT EXISTS lesson_links (
    level       TEXT        NOT NULL CHECK (level IN ('A1', 'A2', 'B2')),
    lesson      INTEGER     NOT NULL,
    url         TEXT        NOT NULL,
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (level, lesson)
  );
`;

/**
 * Segurança no Supabase: tabelas do schema "public" podem ser expostas pela API REST
 * pública (papéis anon/authenticated). Este app NÃO usa essa API — só o servidor fala
 * com o banco, como dono das tabelas. Então:
 *  - RLS ligado em todas as tabelas, sem políticas: anon/authenticated não veem nenhuma linha;
 *  - privilégios revogados desses papéis (defesa em profundidade).
 * O dono das tabelas ignora o RLS, por isso o servidor continua funcionando normalmente.
 */
const TABLES = ['users', 'sessions', 'placement_results', 'modules', 'materials', 'auth_attempts', 'activities',
  'activity_attempts', 'level_changes', 'homework_files', 'lesson_links', 'app_schema'];
const LOCKDOWN = [
  ...TABLES.map((t) => `ALTER TABLE ${t} ENABLE ROW LEVEL SECURITY`),
  `DO $$
   BEGIN
     IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
       REVOKE ALL ON ${TABLES.join(', ')} FROM anon;
     END IF;
     IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticated') THEN
       REVOKE ALL ON ${TABLES.join(', ')} FROM authenticated;
     END IF;
   END $$`,
];

/**
 * Migrações idempotentes para bancos criados por versões anteriores.
 * - Perfil "teacher" (Controle Professor(a)): amplia o CHECK de users.role, só se ainda não aceitar.
 */
const MIGRATIONS = [
  // Senha provisória (redefinida pela professora): o aluno precisa criar uma nova no próximo login.
  'ALTER TABLE users ADD COLUMN IF NOT EXISTS must_change_password BOOLEAN NOT NULL DEFAULT false',
  // Aluno inativo na escola: a professora desliga o acesso (não entra e é desconectado na hora).
  'ALTER TABLE users ADD COLUMN IF NOT EXISTS active BOOLEAN NOT NULL DEFAULT true',
  'ALTER TABLE users ADD COLUMN IF NOT EXISTS deactivated_at TIMESTAMPTZ',
  `DO $$
   DECLARE c record;
   BEGIN
     FOR c IN
       SELECT conname FROM pg_constraint
       WHERE conrelid = 'users'::regclass AND contype = 'c'
         AND pg_get_constraintdef(oid) LIKE '%role%' AND pg_get_constraintdef(oid) NOT LIKE '%teacher%'
     LOOP
       EXECUTE format('ALTER TABLE users DROP CONSTRAINT %I', c.conname);
       ALTER TABLE users ADD CONSTRAINT users_role_check CHECK (role IN ('student', 'admin', 'teacher'));
     END LOOP;
   END $$`,
];

const STATEMENTS = [...SCHEMA.split(';').map((s) => s.trim()).filter(Boolean), ...MIGRATIONS, ...LOCKDOWN];
// Muda sempre que o schema mudar: se o banco já está nesta versão, nada precisa ser recriado.
const SCHEMA_VERSION = require('node:crypto').createHash('sha256').update(STATEMENTS.join('\n')).digest('hex').slice(0, 16);
const RACE_CODES = ['42P07', '23505', '42710'];

let driverPromise = null;

/**
 * Garante o schema com o MÍNIMO de idas ao banco (cada ida custa ~100 ms na Vercel):
 *  - schema em dia → 1 consulta (lê a versão) e pronto;
 *  - schema novo/alterado → todos os comandos em UMA única ida, depois grava a versão.
 * Antes, cada um dos ~45 comandos era uma ida separada a cada "cold start" (vários segundos).
 */
async function ensureSchema(d) {
  try {
    const rows = await d.query('SELECT version FROM app_schema WHERE id = 1');
    if (rows[0]?.version === SCHEMA_VERSION) return;
  } catch (err) {
    if (err.code !== '42P01') throw err; // 42P01 = tabela ainda não existe (banco novo)
  }
  try {
    await d.exec(STATEMENTS.join(';\n'));
  } catch (err) {
    // Duas instâncias subindo ao mesmo tempo podem disputar o CREATE ... IF NOT EXISTS: refaz um a um.
    if (!RACE_CODES.includes(err.code)) throw err;
    for (const stmt of STATEMENTS) {
      try { await d.query(stmt); } catch (e) { if (!RACE_CODES.includes(e.code)) throw e; }
    }
  }
  await d.query(`INSERT INTO app_schema (id, version) VALUES (1, $1)
                 ON CONFLICT (id) DO UPDATE SET version = EXCLUDED.version`, [SCHEMA_VERSION]);
}

async function createDriver() {
  if (DATABASE_URL) {
    const { Pool, types } = require('pg');
    // COUNT(*) e BIGINT chegam como texto no pg; convertemos para número (nossos valores cabem).
    types.setTypeParser(20, (v) => Number(v));
    const isLocal = /@(localhost|127\.0\.0\.1)[:/]/.test(DATABASE_URL);
    const ca = process.env.DATABASE_CA_CERT;
    const pool = new Pool({
      connectionString: DATABASE_URL.replace(/[?&]sslmode=[^&]*/, ''),
      // Serverless: poucas conexões por instância; o pooler do Supabase faz o resto.
      max: Number(process.env.DATABASE_POOL_MAX) || 6,
      idleTimeoutMillis: 10_000,
      // O certificado do Supabase é assinado pela CA própria deles: valide com DATABASE_CA_CERT
      // quando disponível; sem ela, a conexão continua criptografada (TLS) sem verificar a CA.
      ssl: isLocal ? false : (ca ? { ca } : { rejectUnauthorized: false }),
    });
    return {
      query: async (sql, params) => (await pool.query(sql, params)).rows,
      exec: async (sql) => { await pool.query(sql); }, // sem parâmetros: aceita vários comandos de uma vez
      end: () => pool.end(),
    };
  }

  // Na Vercel o disco é somente leitura: sem DATABASE_URL não há banco possível.
  if (IS_VERCEL) {
    throw Object.assign(
      new Error('DATABASE_URL não configurada na Vercel (Settings → Environment Variables) — faça um Redeploy depois de cadastrar.'),
      { code: 'NO_DATABASE_URL' },
    );
  }

  // PGlite: módulo carregado só quando não há DATABASE_URL (dev/testes).
  const pgliteModule = '@electric-sql/pglite';
  const { PGlite } = require(pgliteModule);
  const inMemory = process.env.PGLITE_DIR === 'memory';
  if (!inMemory) fs.mkdirSync(PGLITE_DIR, { recursive: true });
  const pg = inMemory ? new PGlite() : new PGlite(PGLITE_DIR);
  await pg.waitReady;
  const norm = (row) => {
    for (const k of Object.keys(row)) if (typeof row[k] === 'bigint') row[k] = Number(row[k]);
    return row;
  };
  return {
    query: async (sql, params) => (await pg.query(sql, params)).rows.map(norm),
    exec: async (sql) => { await pg.exec(sql); },
    end: () => pg.close(),
  };
}

function driver() {
  if (!driverPromise) {
    driverPromise = (async () => {
      const d = await createDriver();
      await ensureSchema(d);
      return d;
    })().catch((err) => {
      driverPromise = null; // permite nova tentativa na próxima requisição
      throw err;
    });
  }
  return driverPromise;
}

async function query(sql, params = []) {
  return (await driver()).query(sql, params);
}

async function one(sql, params = []) {
  return (await query(sql, params))[0] || null;
}

async function close() {
  if (!driverPromise) return;
  const d = await driverPromise;
  driverPromise = null;
  await d.end();
}

module.exports = { query, one, ready: driver, close, STATEMENTS };
